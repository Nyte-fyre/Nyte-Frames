"""Collect every translatable string in Nyte Frames.

Keys are the English text inside L["..."] / NF.L["..."], plus the slash
help descriptions in NF.HELP (Core/Init.lua).

  python tools/locale_keys.py           rewrite Locales/_template.lua
  python tools/locale_keys.py --check   exit 1 if the template is stale

Translators copy the template to Locales/<code>.lua (deDE, frFR, esES, ...),
fill in the right-hand sides, delete lines they skip (English is used for
those), and add the file to NyteFrames.toc after Core\\Locale.lua.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEMPLATE = os.path.join(ROOT, "Locales", "_template.lua")
SKIP_DIRS = {"Libs", "tests", "tools", "Locales", "private", ".git"}
KEY = re.compile(r'(?:NF\.)?\bL\["((?:[^"\\]|\\.)*)"\]')


def lua_files():
    for d, dirs, files in os.walk(ROOT):
        dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS)
        for f in sorted(files):
            if f.endswith(".lua"):
                yield os.path.join(d, f)


def collect():
    keys = {}
    for path in lua_files():
        rel = os.path.relpath(path, ROOT).replace("\\", "/")
        src = open(path, encoding="utf-8").read()
        for m in KEY.finditer(src):
            keys.setdefault(m.group(1), rel)
        if rel == "Core/Init.lua":
            block = re.search(r"NF\.HELP = \{(.*?)\n\}", src, re.S)
            for m in re.finditer(r'\{ "[^"]*", "((?:[^"\\]|\\.)*)" \}', block.group(1)):
                keys.setdefault(m.group(1), rel)
    return keys


def render(keys):
    out = [
        "-- Nyte Frames translation template (generated by tools/locale_keys.py; do not edit).",
        "-- Copy to Locales/<code>.lua, set the code, translate the right-hand sides,",
        "-- keep %s / %d placeholders in order, and list the file in the TOC.",
        "local _, NF = ...",
        'local L = NF.NewLocale("xxXX")',
        "if not L then return end",
        "",
    ]
    by_file = {}
    for k, f in keys.items():
        by_file.setdefault(f, []).append(k)
    for f in sorted(by_file):
        out.append("-- " + f)
        for k in sorted(by_file[f], key=str.lower):
            out.append('L["%s"] = "%s"' % (k, k))
        out.append("")
    return "\n".join(out)


def main():
    text = render(collect())
    if "--check" in sys.argv:
        cur = open(TEMPLATE, encoding="utf-8").read() if os.path.exists(TEMPLATE) else ""
        if cur.replace("\r\n", "\n") != text:
            print("Locales/_template.lua is stale: run python tools/locale_keys.py")
            return 1
        print("locale template up to date")
        return 0
    os.makedirs(os.path.dirname(TEMPLATE), exist_ok=True)
    open(TEMPLATE, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote %d keys to Locales/_template.lua" % len(collect()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
